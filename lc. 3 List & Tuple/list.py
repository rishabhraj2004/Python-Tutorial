marks = [85, 90, 78] #list banane ke liye hum square bracket ka use karte hai aur usme elements ko comma se separate karte hai
print(marks) #list ko print karne ke liye hum print function ka use karte hai
print(type(marks)) #list ka type check karne ke liye hum type function ka use karte hai
# list ke andar hum different type ke data store kar sakte hai jaise ki int, float, string, boolean etc
print(marks[0]) #list ke first element ko access karne ke liye hum index 0 ka use karte hai
print(marks[1]) #list ke second element ko access karne ke liye hum index 1 ka use karte hai
print(len(marks)) #list ke length ko check karne ke liye hum len function ka use karte hai
