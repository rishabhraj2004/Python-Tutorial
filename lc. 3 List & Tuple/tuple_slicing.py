num = (1, 2, 3,4)
print(num[1:3])  # Output: (2, 3) index 1 se 2 tak ke elements print karega
print(num[:2])   # Output: (1, 2) index 0 se 1 tak ke elements print karega
print(num[2:])   # Output: (3, 4) index 2 se end tak ke elements print karega
print(num[:])    # Output: (1, 2, 3, 4) tuple ke sare elements print karega
print(num[-3:-1])  # Output: (2, 3) negative indexing   ka use karke last se 3rd element se last se 1st element tak ke elements print karega
