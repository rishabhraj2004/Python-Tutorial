marks = [85, 94, 76, 54, 84]
print(marks[1:4])  # Output: [94, 76, 54]
print(marks[:3])   # Output: [85, 94, 76] index 0 se 2 tak ke elements print karega
print(marks[2:])   # Output: [76, 54, 84] index 2 se end tak ke elements print karega
print(marks[:])    # Output: [85, 94, 76, 54, 84] list ke sare elements print karega
print(marks[-3:-1])  # Output: [76, 54] negative indexing ka use karke last se 3rd element se last se 1st element tak ke elements print karega